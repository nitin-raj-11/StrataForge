import { useMemo, useState } from 'react'
import type { Trade } from '../../api/types'
import { formatCurrency, formatDate, formatPercent, gainLossClass } from '../../lib/format'

type SortKey = keyof Trade
type SortDir = 'asc' | 'desc'

const COLUMNS: { key: SortKey; label: string }[] = [
  { key: 'entryDate', label: 'Entry date' },
  { key: 'exitDate', label: 'Exit date' },
  { key: 'entryPrice', label: 'Entry price' },
  { key: 'exitPrice', label: 'Exit price' },
  { key: 'pnl', label: 'P&L' },
  { key: 'pnlPercent', label: 'P&L %' },
]

export default function TradeLogTable({ trades }: { trades: Trade[] }) {
  const [sortKey, setSortKey] = useState<SortKey>('entryDate')
  const [sortDir, setSortDir] = useState<SortDir>('asc')

  const sorted = useMemo(() => {
    const copy = [...trades]
    copy.sort((a, b) => {
      const av = a[sortKey]
      const bv = b[sortKey]
      const cmp = typeof av === 'string' ? av.localeCompare(bv as string) : (av as number) - (bv as number)
      return sortDir === 'asc' ? cmp : -cmp
    })
    return copy
  }, [trades, sortKey, sortDir])

  function toggleSort(key: SortKey) {
    if (key === sortKey) {
      setSortDir((d) => (d === 'asc' ? 'desc' : 'asc'))
    } else {
      setSortKey(key)
      setSortDir('asc')
    }
  }

  if (trades.length === 0) {
    return (
      <div className="text-center py-14 text-ink-faint">
        <p className="text-[14px]">No trades were generated by this strategy over this period.</p>
        <p className="text-[12px] mt-1">Try widening the date range or loosening the entry condition.</p>
      </div>
    )
  }

  return (
    <div className="overflow-x-auto -mx-1">
      <table className="w-full text-[13px] min-w-[640px]">
        <thead>
          <tr className="border-b border-base-border text-left">
            {COLUMNS.map((col) => (
              <th key={col.key} className="px-3 py-2.5">
                <button
                  type="button"
                  onClick={() => toggleSort(col.key)}
                  className="flex items-center gap-1 text-ink-faint hover:text-ink-primary transition uppercase tracking-wide text-[11px] font-medium"
                >
                  {col.label}
                  {sortKey === col.key && <span className="text-accent-amber">{sortDir === 'asc' ? '↑' : '↓'}</span>}
                </button>
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {sorted.map((t, i) => (
            <tr key={i} className="border-b border-base-borderMuted hover:bg-white/[0.015]">
              <td className="px-3 py-2.5 mono-num text-ink-muted">{formatDate(t.entryDate)}</td>
              <td className="px-3 py-2.5 mono-num text-ink-muted">{formatDate(t.exitDate)}</td>
              <td className="px-3 py-2.5 mono-num">{formatCurrency(t.entryPrice)}</td>
              <td className="px-3 py-2.5 mono-num">{formatCurrency(t.exitPrice)}</td>
              <td className={`px-3 py-2.5 mono-num font-medium ${gainLossClass(t.pnl)}`}>
                {formatCurrency(t.pnl)}
              </td>
              <td className={`px-3 py-2.5 mono-num font-medium ${gainLossClass(t.pnlPercent)}`}>
                {formatPercent(t.pnlPercent)}
              </td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  )
}
